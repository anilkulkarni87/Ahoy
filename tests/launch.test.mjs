test('launch requires current preview, blocks inflight and leaves other workspaces untouched',async()=>{
 const p=await launchPreview('owner');
 await assert.rejects(prepareLaunch('owner','DELETE',p.fingerprint),/PREPARE/);
 await db().execute("UPDATE activity SET status='sending' WHERE id='pending'");
 await assert.rejects(prepareLaunch('owner','PREPARE',p.fingerprint),/running/);
 await db().execute("UPDATE activity SET status='queued' WHERE id='pending'");
 await db().execute("INSERT INTO activity(id,tenant,comment_id,username,comment,status) VALUES('extra','owner','extra','person','hi','skipped')");
 await assert.rejects(prepareLaunch('owner','PREPARE',p.fingerprint),/changed/);
 await db().execute("INSERT INTO campaigns VALUES('other','other','{\"active\":true}',CURRENT_TIMESTAMP)");
 const fresh=await launchPreview('owner');const result=await prepareLaunch('owner','PREPARE',fresh.fingerprint);
 assert.ok(result.analyticsSince);
 assert.equal(JSON.parse((await db().execute("SELECT data FROM campaigns WHERE id='c'")).rows[0].data).active,false);
 assert.equal(JSON.parse((await db().execute("SELECT data FROM campaigns WHERE id='other'")).rows[0].data).active,true);
 assert.equal((await db().execute("SELECT status FROM activity WHERE id='pending'")).rows[0].status,'skipped');
 for(const table of ['accounts','opt_outs','links'])assert.equal((await db().execute(`SELECT count(*) AS n FROM ${table} WHERE tenant='owner'`)).rows[0].n,1);
 assert.equal((await db().execute("SELECT count(*) AS n FROM archived_links WHERE tenant='owner'")).rows[0].n,1);
 assert.deepEqual(await deliver('pending'),{skipped:true});
 assert.equal((await checkFollow({id:'pending',eventId:'late'})).skipped,true);
 await db().execute({sql:'UPDATE campaigns SET data=? WHERE id=?',args:[JSON.stringify(c),'c']});
 for(const timestamp of [undefined,'invalid','2020-01-01T00:00:00Z'])assert.equal((await processComment('owner',{commentId:String(timestamp),username:'person',text:'guide',accountId:'ig',timestamp})).status,'skipped');
 const duplicate=await processComment('owner',{commentId:'old',username:'person',text:'guide',accountId:'ig',timestamp:new Date().toISOString()});assert.equal(duplicate.duplicate,true);
 assert.equal((await processComment('owner',{commentId:'new',username:'person',text:'guide',accountId:'ig',timestamp:new Date().toISOString()})).status,'queued');
});
