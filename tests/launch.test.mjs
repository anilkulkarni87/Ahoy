import assert from 'node:assert/strict';
import {mkdtempSync} from 'node:fs';import {tmpdir} from 'node:os';import {join} from 'node:path';
process.env.DATABASE_URL='file:'+join(mkdtempSync(join(tmpdir(),'ahoy-launch-')),'test.db');
const {db,init}=await import('../lib/db.mjs');
const {launchPreview,prepareLaunch,beforeLaunch}=await import('../lib/launch.mjs');
const {processComment,deliver}=await import('../lib/engine.mjs');
const {checkFollow}=await import('../lib/follow.mjs');
await init();
const c={active:true,accountId:'ig',triggerType:'any',keywords:['guide'],ignoreCase:true,matchMode:'contains',dmTemplate:'resource'};
await db().execute({sql:'INSERT INTO campaigns VALUES(?,?,?,CURRENT_TIMESTAMP)',args:['c','owner',JSON.stringify(c)]});
await db().execute("INSERT INTO accounts(id,tenant,username,token) VALUES('ig','owner','studio','keep-encrypted')");
